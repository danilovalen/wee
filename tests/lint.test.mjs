// Lint warnings, and the saved-solution check.
import { lint, brokenAt } from '../src/solve/lint.js';
import { solve } from '../src/solve/solve.js';
import { room, suite } from './lib.mjs';

const { check, done } = suite('lint');
const has = (l, text) => lint(l).some(w => w.msg.includes(text));
check('a clean room has no warnings', lint(room(['#####', '#P.o#', '#..D#', '#####'])).length === 0, JSON.stringify(lint(room(['#####', '#P.o#', '#..D#', '#####']))));
const nd = room(['#####', '#P..#', '#..D#', '#####']);
check('a door with no switch of its colour', has(nd, 'With no red button, switch or relay, the red door never changes.') && lint(nd)[0].x === 3 && lint(nd)[0].y === 2);
const id = room(['#####', '#P..#', '#...#', '#####']); id.cells[11] = 'idoor:blue';
check('an inverted door is named as one', has(id, 'the blue inverted door never changes'));
check('a button with nothing to drive is named a button, with doesn\'t (registers 743, 747)', has(room(['#####', '#Po.#', '#####']), 'With no red door or one-way, the red button doesn\'t do anything.'));
check('a laser relay is named a relay', has(room(['#####', '#Pr.#', '#####']), 'the red relay doesn\'t do anything'));
const ow = room(['######', '#Po..#', '######']); ow.cells[9] = 'gate:right@red';
check('a red one-way counts as what a red button drives (register 747)', lint(ow).length === 0, JSON.stringify(lint(ow)));
const lg = room(['######', '#P...#', '######']); lg.cells[9] = 'gate:right@blue';
check('a blue one-way with nothing blue to drive it is named', has(lg, 'the blue one-way never changes'));
const gw = room(['#####', '#P..#', '#####']); gw.cells[7] = 'button:wire';
check('grey works through wires and is left out', lint(gw).length === 0);
const tw = room(['#####', '#Pe.#', '#####']); tw.entities[0].turret.dirs = ['up'];
check('a turret aimed into a block', has(tw, 'Aimed up into a block, the laser'));
const ts = room(['#####', '#Pe.#', '#####']); ts.cells[8] = 'spring:up';
check('a spring counts as a block for a turret', lint(ts).some(w => w.msg.includes('Aimed right into a block')));
check('a turret aimed into open floor is fine', !has(room(['#####', '#Pe.#', '#####']), 'into a block'));
const boxed = room(['#####', '#P#.#', '##B##', '#####']);
check('a piece walled in on every side', has(boxed, 'piece is walled in'));
check('the start walled in', has(room(['#####', '#P#.#', '##..#', '#####']), 'start is walled in'));
check('a turret in a corner is not a walled-in piece', !has(room(['###', '#e#', '###']), 'piece is walled in'));
const g = room(['#####', '#P..#', '#####']); g.cells[8] = 'goal';
const sol = solve(g).moves;
check('a saved solution that still wins is not broken', brokenAt(g, sol) === 0);
const moved = JSON.parse(JSON.stringify(g)); moved.cells[8] = ''; moved.cells[7] = 'goal';
check('one that no longer reaches the goal is broken at its last move', brokenAt(moved, sol) === 1);
const deadly = JSON.parse(JSON.stringify(g)); deadly.cells[7] = 'death';
check('one that now dies says on which move', brokenAt(deadly, ['right', 'left']) === 1);
done();
